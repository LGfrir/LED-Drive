def text_height(pdf, width, text, size, line_h):
    pdf.set_font("yh", size=size)
    lines = pdf.multi_cell(width, line_h, text, dry_run=True, output="LINES", align="L")
    return max(line_h, len(lines) * line_h)


def paint_row(pdf, label, text, label_bg):
    label_w = 16
    gap = 0
    body_w = pdf.epw - label_w - gap
    line_h = 7.4
    inner_w = body_w - 4
    body_h = text_height(pdf, inner_w, text, 13.5, line_h)
    height = max(16, body_h + 4)
    if pdf.get_y() + height > pdf.h - pdf.b_margin:
        pdf.add_page()
    x = pdf.l_margin
    y = pdf.get_y()
    pdf.set_fill_color(*label_bg)
    pdf.rect(x, y, label_w, height, "F")
    pdf.set_fill_color(*BODY)
    pdf.rect(x + label_w, y, body_w, height, "F")
    pdf.set_draw_color(210, 214, 218)
    pdf.rect(x, y, label_w + body_w, height, "D")
    pdf.set_xy(x + 1, y + 2)
    pdf.set_font("yh", "B", 11)
    pdf.set_text_color(40, 48, 44)
    pdf.multi_cell(label_w - 2, 5.5, label, align="C")
    pdf.set_xy(x + label_w + 2, y + 2)
    pdf.set_font("yh", size=13.5)
    pdf.set_text_color(24, 28, 32)
    pdf.multi_cell(inner_w, line_h, text, align="L")
    pdf.set_xy(x, y + height)


def add_issue(pdf, item):
    title = f"{item['id']}  {item['name']}"
    pdf.set_font("yh", "B", 15)
    title_h = text_height(pdf, pdf.epw - 4, title, 15, 7.6) + 5
    # 预估两格高度，尽量整卡留在同一页；太长就允许从标题后拆开
    sample_cause = text_height(pdf, pdf.epw - 20, item["cause"], 13.5, 7.4) + 4
    sample_fix = text_height(pdf, pdf.epw - 20, item["solution"], 13.5, 7.4) + 4
    need = title_h + sample_cause + sample_fix + 4
    room = pdf.h - pdf.b_margin - pdf.get_y()
    if need < (pdf.h - pdf.t_margin - pdf.b_margin) and room < need:
        pdf.add_page()
    color = KIND_COLOR[item["kind"]]
    y = pdf.get_y()
    pdf.set_fill_color(*color)
    pdf.rect(pdf.l_margin, y, pdf.epw, title_h, "F")
    pdf.set_xy(pdf.l_margin + 2, y + 2.2)
    pdf.set_font("yh", "B", 15)
    pdf.set_text_color(255, 255, 255)
    pdf.multi_cell(pdf.epw - 4, 7.6, title, align="L")
    pdf.set_xy(pdf.l_margin, y + title_h)
    kind_line = item["kind"]
    pdf.set_font("yh", size=10)
