def main():
    data = issues()
    pdf = Doc()
    pdf.set_margins(8, 10, 8)
    add_cover(pdf)
    current = None
    for item in data:
        if item["chapter"] != current:
            current = item["chapter"]
            pdf.add_page()
            pdf.chapter = current
            pdf.start_section(current, level=0)
            pdf.set_font("yh", "B", 18)
            pdf.set_text_color(*KIND_COLOR.get("本轮修", (22, 72, 92)))
            if "待定" in current or current.startswith("先看"):
                pdf.set_text_color(*KIND_COLOR["待定"])
            elif current.startswith("第二轮"):
                pdf.set_text_color(*KIND_COLOR["第二轮"])
            elif current.startswith("核对"):
                pdf.set_text_color(*KIND_COLOR["不修"])
            pdf.multi_cell(0, 9, current, align="L")
            pdf.ln(2)
        pdf.chapter = current
        pdf.start_section(f"{item['id']} {item['name']}", level=1)
        add_issue(pdf, item)
    for path in OUTS:
        pdf.output(path)
        print(path, "pages", pdf.page)


if __name__ == "__main__":
    main()
